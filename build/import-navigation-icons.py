def geometry(svg):
    root=ET.fromstring(svg)
    assert root.attrib['viewBox']=='0 0 24 24' and root.attrib['stroke-width']=='2' and root.attrib['fill']=='none'
    parts=[]
    for element in root:
        tag=element.tag.split('}')[-1];a=element.attrib
        assert 'transform' not in a
        if tag=='path':
            tokens=re.findall(r'[A-Za-z]|[-+]?(?:\d*\.?\d+)(?:[eE][-+]?\d+)?',a['d'])
            # Each SVG <path> starts at its own origin. Normalize its initial relative
            # moveto before combining paths, preserving implicit relative lineto pairs.
            if tokens[0]=='m':
                tokens[0]='M'
                if len(tokens)>3 and tokens[3] not in 'MmLlHhVvCcSsQqTtAaZz':tokens.insert(3,'l')
            parts.append(' '.join(tokens))
        elif tag in ('circle','ellipse'):
            x=float(a['cx']);y=float(a['cy']);rx=float(a.get('rx',a.get('r')));ry=float(a.get('ry',a.get('r')))
            parts.append(f'M{x+rx} {y} A{rx} {ry} 0 1 1 {x-rx} {y} A{rx} {ry} 0 1 1 {x+rx} {y} Z')
        elif tag=='rect':
            x=float(a.get('x',0));y=float(a.get('y',0));w=float(a['width']);h=float(a['height']);rx=min(float(a.get('rx',0)),w/2);ry=min(float(a.get('ry',rx)),h/2)
            if rx and ry:parts.append(f'M{x+rx} {y} H{x+w-rx} A{rx} {ry} 0 0 1 {x+w} {y+ry} V{y+h-ry} A{rx} {ry} 0 0 1 {x+w-rx} {y+h} H{x+rx} A{rx} {ry} 0 0 1 {x} {y+h-ry} V{y+ry} A{rx} {ry} 0 0 1 {x+rx} {y} Z')
            else:parts.append(f'M{x} {y} H{x+w} V{y+h} H{x} Z')
        elif tag=='line':parts.append(f'M{a["x1"]} {a["y1"]} L{a["x2"]} {a["y2"]}')
        elif tag in ('polyline','polygon'):parts.append('M'+a['points']+(' Z' if tag=='polygon' else ''))
        else:raise ValueError('Unsupported SVG primitive: '+tag)
    return ' '.join(re.findall(r'[A-Za-z]|[-+]?(?:\d*\.?\d+)(?:[eE][-+]?\d+)?',' '.join(parts)))

